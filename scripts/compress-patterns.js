// Pattern Compression Script
// Compresses multiple decision records into reusable patterns

const fs = require('fs');
const path = require('path');

function compressDecisionRecords() {
  console.log('Compressing decision records...\n');
  
  const recordsDir = path.join(process.cwd(), '.ai', 'decision-records');
  const patternsDir = path.join(process.cwd(), '.ai', 'patterns');
  
  // Create patterns directory if not exists
  if (!fs.existsSync(patternsDir)) {
    fs.mkdirSync(patternsDir, { recursive: true });
  }
  
  // Get all decision records
  if (!fs.existsSync(recordsDir)) {
    console.log('⚠ No decision records directory found');
    return;
  }
  
  const files = fs.readdirSync(recordsDir)
    .filter(f => f.startsWith('DR-') && f.endsWith('.md'));
  
  if (files.length === 0) {
    console.log('⚠ No decision records found');
    console.log('  Create DR files in .ai/decision-records/');
    return;
  }
  
  console.log(`Found ${files.length} decision records\n`);
  
  // Parse decision records
  const records = files.map(f => {
    const content = fs.readFileSync(path.join(recordsDir, f), 'utf-8');
    return {
      id: f.replace('.md', ''),
      file: f,
      category: extractCategory(content),
      approach: extractApproach(content),
      decision: extractDecision(content)
    };
  });
  
  // Group by pattern
  const patterns = {};
  
  records.forEach(record => {
    const key = `${record.category}-${record.approach}`;
    
    if (!patterns[key]) {
      patterns[key] = {
        pattern: record.decision,
        examples: [],
        count: 0
      };
    }
    
    patterns[key].examples.push(record.id);
    patterns[key].count++;
  });
  
  // Create compressed pattern files
  let compressedCount = 0;
  
  Object.entries(patterns).forEach(([key, pattern]) => {
    if (pattern.count >= 3) {  // Threshold for compression
      const patternFile = path.join(patternsDir, `PATTERN-${key}.md`);
      
      const content = `# PATTERN: ${pattern.pattern}

## Context
Repeated decision pattern detected from ${pattern.count} implementations

## Examples
${pattern.examples.map(e => `- ${e}`).join('\n')}

## Count: ${pattern.count}

## Confidence: ★★★★☆

## Last Updated: ${new Date().toISOString().split('T')[0]}

---

**Auto-generated by pattern compression script**
`;
      
      fs.writeFileSync(patternFile, content);
      console.log(`✓ Compressed ${pattern.count} decisions into PATTERN-${key}`);
      compressedCount++;
    }
  });
  
  if (compressedCount === 0) {
    console.log('⚠ No patterns met threshold (3+ similar decisions)');
    console.log('  Keep adding decision records for pattern detection\n');
  } else {
    console.log(`\n✓ ${compressedCount} patterns created in ${patternsDir}\n`);
  }
}

function extractCategory(content) {
  const match = content.match(/## Decision\s+(.+?)(?:\n|$)/);
  return match ? match[1].toLowerCase().replace(/\s+/g, '-') : 'general';
}

function extractApproach(content) {
  const match = content.match(/\*\*Chosen:\*\*\s+(.+?)(?:\n|$)/);
  return match ? match[1].toLowerCase().replace(/\s+/g, '-') : 'default';
}

function extractDecision(content) {
  const match = content.match(/## Decision\s+(.+?)(?:\n|$)/);
  return match ? match[1].trim() : 'Unknown decision';
}

compressDecisionRecords();
